import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const web = resolve(app, "../web_dashboard");
const check = process.argv.includes("--check");
function sync(source, target) {
  const bytes = readFileSync(resolve(web, source));
  const destination = resolve(app, target);
  if (check) {
    if (!bytes.equals(readFileSync(destination))) throw new Error(`Chưa đồng bộ: ${target}`);
  } else {
    mkdirSync(dirname(destination), { recursive: true });
    copyFileSync(resolve(web, source), destination);
  }
}
for (const file of ["programs.ts", "publicWebsite.ts", "publicContent.ts"]) sync(`models/${file}`, `src/content/${file}`);
for (const file of ["pp-academy-logo.png", "pp-academy-campus.webp", "pp-academy-library.webp", "pp-academy-tech-lab.webp"]) sync(`public/${file}`, `src/assets/brand/${file}`);
const source = readFileSync(resolve(web, "views/public/HeroVideos.tsx"), "utf8");
const clips = [...source.matchAll(/src: "\/videos\/([^"/]+\.mp4)", label: "([^"]+)"/g)];
if (!clips.length) throw new Error("Không đọc được danh sách video của web");
for (const [, file] of clips) sync(`public/videos/${file}`, `src/assets/videos/${file}`);
const manifest = `// Generated by npm run sync:website from the web video playlist.\nexport const homeClips = [\n${clips.map(([, file, label]) => `  { label: ${JSON.stringify(label)}, source: require("../assets/videos/${file}") },`).join("\n")}\n];\n`;
const target = resolve(app, "src/content/homeVideos.ts");
if (check) {
  if (readFileSync(target, "utf8") !== manifest) throw new Error("Danh sách video chưa đồng bộ");
} else writeFileSync(target, manifest);
console.log(`${check ? "Đã kiểm tra" : "Đã đồng bộ"} nội dung, logo, ảnh và ${clips.length} video từ web.`);
